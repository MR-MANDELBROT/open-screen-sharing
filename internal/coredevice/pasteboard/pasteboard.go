// The DDI's CoreDeviceUtilities declares these as
// PasteboardDataInclusionPolicy cases and Codable keys (CoreDeviceUtilities
// 651.13.2, DDI 27A9266e, UUID 93303947-1F03-3EF7-8EB1-2AF348389899, field
// descriptor 0x475a30, sub_2d2cc8 0x2d2cc8..0x2d2d80).
var (
	policyPromiseSecondary = map[string]any{"promiseSecondary": map[string]any{}}
	policyAllPromised      = map[string]any{"allPromised": map[string]any{}}
)

type Client struct {
	device *coredevice.Device
	logger *slog.Logger
	nonce  string
	writes int64

	access        sync.Mutex
	own           []change
	sent          map[[sha1.Size]byte]time.Time
	pendingWrites int
	writesDone    chan struct{}
}

const (
	ownChangesKept = 16
	echoWindow     = 3 * time.Second
)

func New(device *coredevice.Device, logger *slog.Logger) *Client {
	return &Client{device: device, logger: logger, nonce: uuid.NewString(), sent: make(map[[sha1.Size]byte]time.Time)}
}

type Snapshot struct {
	Items []Item

	change change
}

type Item struct {
	Types []string
	Data  map[string][]byte
}

type change struct {
	nonce any
	count any
}

func (c change) valid() bool {
	return c.count != nil
}

func (c change) equal(other change) bool {
	return c.valid() && reflect.DeepEqual(c, other)
}

func (s Snapshot) Text() (string, bool) {
	for _, item := range s.Items {
		for _, textType := range textTypes {
			data := item.Data[textType]
			if len(data) == 0 || !utf8.Valid(data) {
				continue
			}
			text := string(data)
			if strings.Trim(text, "￼ \t\r\n") == "" {
				if _, _, hasImage := s.Image(); hasImage {
					return "", false
				}
			}
			return text, true
		}
	}
	return "", false
}

func (s Snapshot) Image() (imageType string, data []byte, ok bool) {
	for _, item := range s.Items {
		for _, image := range imageMIMETypes {
			if data := item.Data[image.uti]; len(data) > 0 {
				return image.uti, data, true
			}
		}
	}
	for _, item := range s.Items {
		if archive := item.Data[TypeWebArchive]; len(archive) > 0 {
			if imageType, data, ok = webArchiveImage(archive); ok {
				return imageType, data, true
			}
		}
	}
	return "", nil, false
}

func webArchiveImage(archive []byte) (imageType string, data []byte, ok bool) {
	// howett.net/plist re-panics runtime.Error in both the binary parser and
	// Decoder.Decode (howett.net/plist v1.0.1, bplist_parser.go:65-74;
	// howett.net/plist v1.0.1, decode.go:26-35).
	defer func() {
		if recover() != nil {
			imageType, data, ok = "", nil, false
		}
	}()
	var parsed struct {
		Subresources []struct {
			MIMEType string `plist:"WebResourceMIMEType"`
			Data     []byte `plist:"WebResourceData"`
		} `plist:"WebSubresources"`
	}
	if _, err := plist.Unmarshal(archive, &parsed); err != nil {
		return "", nil, false
	}
	for _, resource := range parsed.Subresources {
		for _, image := range imageMIMETypes {
			if resource.MIMEType == image.mime && len(resource.Data) > 0 {
				return image.uti, resource.Data, true
			}
		}
	}
	return "", nil, false
}

func (s Snapshot) Empty() bool {
	_, hasText := s.Text()
	_, _, hasImage := s.Image()
	return !hasText && !hasImage
}

func (s Snapshot) Concealed() bool {
	return slices.ContainsFunc(s.Items, func(item Item) bool {
		return slices.ContainsFunc(concealedTypes, func(concealedType string) bool {
			return slices.Contains(item.Types, concealedType)
		})
	})
}

func (c *Client) Read(ctx context.Context) (Snapshot, error) {
	return c.pull(ctx, policyPromiseSecondary)
}

func (c *Client) pull(ctx context.Context, policy map[string]any) (Snapshot, error) {
	if _, hasDeadline := ctx.Deadline(); !hasDeadline {
		var cancel context.CancelFunc
		ctx, cancel = context.WithTimeout(ctx, defaultRequestTimeout)
		defer cancel()
	}
	conn, err := c.device.DialXPC(ctx, service)
	if err != nil {
		return Snapshot{}, E.Cause(err, "pasteboard")
	}
	defer conn.Close()
	reply, err := conn.Request(ctx, map[string]any{
		"command":        "PULL",
		"pasteboardName": general,
		"dataPolicy":     policy,
	})
	if err != nil {
		return Snapshot{}, E.Cause(err, "pasteboard: PULL")
	}
	return snapshotReply(reply, "PULL_REPLY")
}

func (c *Client) WriteText(ctx context.Context, text string, written func(error)) error {
	data := make(map[string]any, len(textTypes))
	for _, textType := range textTypes {
		data[textType] = map[string]any{"data": []byte(text)}
	}
	return c.write(ctx, map[string]any{"types": textTypes, "data": data}, []byte(text), written)
}

func (c *Client) WriteImage(ctx context.Context, imageType string, image []byte, written func(error)) error {
	return c.write(ctx, map[string]any{
		"types": []string{imageType},
		"data":  map[string]any{imageType: map[string]any{"data": image}},
	}, image, written)
}

func (c *Client) write(ctx context.Context, item map[string]any, payload []byte, written func(error)) error {
	fingerprint := sha1.Sum(payload)
	c.noteSent(fingerprint)
	conn, err := c.device.DialXPC(ctx, service)
	if err != nil {
		return E.Cause(err, "pasteboard")
	}
	stop := context.AfterFunc(ctx, func() { conn.Close() })
	err = conn.Send(map[string]any{
		"command":        "SET",
		"pasteboardName": general,
		"items":          []any{item},
		"sourceMetadata": c.sourceMetadata(),
	}, true)
	if !stop() {
		err = ctx.Err()
	}
	if err != nil {
		conn.Close()
		return E.Cause(err, "pasteboard: send SET")
	}
	c.access.Lock()
	if c.pendingWrites == 0 {
		c.writesDone = make(chan struct{})
	}
	c.pendingWrites++
	c.access.Unlock()
	go c.finishWrite(conn, fingerprint, written)
	return nil
}

// The DDI's CoreDeviceUtilities loads the snapshot sourceMetadata optional
// and passes its presence as localOnly to
// setItemProviders:localOnly:expirationDate: (CoreDeviceUtilities 651.13.2,
// DDI 27A9266e, UUID 93303947-1F03-3EF7-8EB1-2AF348389899, sub_2c1744
// 0x2c17e4..0x2c1800, 0x2c24e8..0x2c24fc).
func (c *Client) sourceMetadata() map[string]any {
	c.writes++
	return map[string]any{"nonce": c.nonce, "pasteboardName": general, "changeCount": c.writes}
}

func (c *Client) finishWrite(conn *xpc.Conn, fingerprint [sha1.Size]byte, written func(error)) {
	timer := time.AfterFunc(writeReplyTimeout, func() { conn.Close() })
	reply, err := conn.Receive()
	expired := !timer.Stop()
	conn.Close()
	var snapshot Snapshot
	switch {
	case err != nil && expired:
		err = E.New("pasteboard: no SET_REPLY in ", writeReplyTimeout)
	case err != nil:
		err = E.Cause(err, "pasteboard: receive SET_REPLY")
	default:
		snapshot, err = snapshotReply(reply, "SET_REPLY")
	}
	c.access.Lock()
	if err == nil {
		if snapshot.change.valid() {
			c.own = append(c.own, snapshot.change)
			if len(c.own) > ownChangesKept {
				c.own = slices.Delete(c.own, 0, len(c.own)-ownChangesKept)
			}
		}
		c.sent[fingerprint] = time.Now()
	}
	c.pendingWrites--
	if c.pendingWrites == 0 {
		close(c.writesDone)
	}
	c.access.Unlock()
	written(err)
}

func (c *Client) noteSent(fingerprint [sha1.Size]byte) {
	c.access.Lock()
	defer c.access.Unlock()
	now := time.Now()
	maps.DeleteFunc(c.sent, func(_ [sha1.Size]byte, at time.Time) bool {
		return now.Sub(at) >= echoWindow
	})
	c.sent[fingerprint] = now
}

func (c *Client) waitWrites(ctx context.Context, limit time.Duration) {
	c.access.Lock()
	pending, done := c.pendingWrites, c.writesDone
	c.access.Unlock()
	if pending == 0 {
		return
	}
	timer := time.NewTimer(limit)
	defer timer.Stop()
	select {
	case <-done:
	case <-timer.C:
	case <-ctx.Done():
	}
}

func (c *Client) isOwn(snapshot Snapshot) bool {
	c.access.Lock()
	defer c.access.Unlock()
	if slices.ContainsFunc(c.own, snapshot.change.equal) {
		return true
	}
	var payload []byte
	if _, image, ok := snapshot.Image(); ok {
		payload = image
	} else if text, ok := snapshot.Text(); ok {
		payload = []byte(text)
	} else {
		return false
	}
	at, ok := c.sent[sha1.Sum(payload)]
	return ok && time.Since(at) < echoWindow
}

// dtpasteboardd answers a request it refuses or fails with a dictionary that
// holds only an encoded NSError under "error". It refuses a PULL while an item
// on the pasteboard has a restricted type, or a confidential type unless the
// device's pasteboardSyncConfidentialItems default is set (dtpasteboardd
// 651.13.2, DDI 27A9266e, UUID FD90C1A2-FAF6-394A-8D29-06065D7EB459,
// sub_1000227ac 0x100022910..0x1000229e0, sub_10000f3d8 0x10000f5c0..0x10000f698,
// sub_100010364 0x1000106c0..0x1000107dc; CoreDeviceUtilities 651.13.2, DDI
// 27A9266e, UUID 93303947-1F03-3EF7-8EB1-2AF348389899, sub_2bfc14
// 0x2bfdb4..0x2c0050).
var errRefused = E.New("pasteboard: the device refused the request")

func snapshotReply(reply map[string]any, replyCommand string) (Snapshot, error) {
	if _, refused := reply["error"]; refused {
		return Snapshot{}, errRefused
	}
	if command, _ := reply["command"].(string); command != replyCommand {
		return Snapshot{}, E.New("pasteboard: got ", strconv.Quote(command), ", want ", replyCommand)
	}
	pasteboard, ok := reply["pasteboard"].(map[string]any)
	if !ok {
		return Snapshot{}, E.New("pasteboard: ", replyCommand, " without a pasteboard")
	}
	return parseSnapshot(pasteboard), nil
}

func parseSnapshot(pasteboard map[string]any) Snapshot {
	metadata, _ := pasteboard["metadata"].(map[string]any)
	items, _ := pasteboard["items"].([]any)
	return Snapshot{
		Items: common.Map(items, func(value any) Item {
			entry, _ := value.(map[string]any)
			types, _ := entry["types"].([]any)
			item := Item{Types: common.FilterIsInstance(types, func(it any) (string, bool) {
				itemType, ok := it.(string)
				return itemType, ok
			})}
			representations, _ := entry["data"].(map[string]any)
			for itemType, representation := range representations {
				representation, _ := representation.(map[string]any)
				if data, ok := representation["data"].([]byte); ok {
					if item.Data == nil {
						item.Data = make(map[string][]byte)
					}
					item.Data[itemType] = data
				}
			}
			return item
		}),
		change: change{nonce: metadata["nonce"], count: metadata["changeCount"]},
	}
}
